//Section A – OOP Fundamentals (5 × 2 = 10 Marks)
//1. A Student class contains name, age, and marks. 
//These fields must not be directly accessed or modified from outside the class. Which OOP concept should be used? State one reason.
//Answer: Encapsulation
// It protects data from direct access by using private variables.


// 2. A Car class reuses common properties and methods from a Vehicle class. 
//Identify the OOP concept and write the basic Java inheritance syntax.
//Answer: Inheritance
//Syntax: class Car extends Vehicle
// One class can acquire the properties and methods of another class.

//3. A Calculator class has add(int, int), add(int,int,int), and add(double, double) methods. 
//Identify the concept demonstrated.
//Answer: Method Overloading
// Having the same method name with different parameters in the same class is called Method Overloading.

//4. A parent class has a display() method, and a child class provides its own implementation of
//display(). What is this called?
//Answer: Method Overriding
// A child class provides its own implementation of a parent class method with the same name and parameters.

//5. A program must hide implementation details and expose only essential operations. Which OOP concept supports this? Name one Java feature used to achieve it.
//Answer: Abstraction
//Java features:
//Abstract Class
//Interface
// It hides implementation details and shows only essential features.